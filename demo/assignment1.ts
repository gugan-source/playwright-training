//Area of square
let side: number = 3; // value store in side variable

let area: number = side * side; //side already has the value 3, so area will be 3 * 3 = 9

console.log("Area of square =", area);

//Average of three numbers
let numbers: number[] = [10, 20, 30];

let average: number = (numbers[0] + numbers[1] + numbers[2]) / numbers.length;

console.log("Average =", average);

//Division of two numbers
let num1: number = 20;
let num2: number = 5;

let division: number = num1 / num2;

console.log("Division =", division);

//Area of a rectangle
let length1: number = 10;
let breadth: number = 5;

let area1: number = length1 * breadth;

console.log("Area of rectangle =", area1);

